  final ranges = <String>[];
  int category(int cp) => cp <= 0xffff ? table.low(cp) : table.high((cp - 0x10000) >> 10, cp & 1023);
  var start = 0;
  var previous = category(0);
  for (var cp = 1; cp <= 0x110000; cp++) {
    final next = cp == 0x110000 ? -1 : category(cp);
    if (next != previous) {
      ranges.add('($start,${cp - 1},$previous)');
      start = cp;
      previous = next;
    }
  }
  final transitions = <int>[];
  for (var state = 0; state <= constants.stateSoT; state += constants.automatonRowLength) {
    for (var cat = 0; cat < constants.automatonRowLength; cat++) {
      transitions.add(cat < constants.categoryCount ? table.move(state, cat) : 0);
    }
  }
